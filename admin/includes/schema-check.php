// SQL কমেন্ট ছেঁটে ফেলা — `--` লাইন ও `/* … */` ব্লক। 🔴 পার্স করার আগে এটা
// চালাতেই হবে: এই রিপোর মাইগ্রেশনে বাংলা কমেন্ট ভরা, আর সেখানে "ADD COLUMN"
// জাতীয় কথা উদাহরণ হিসেবে লেখা থাকতে পারে — তাহলে না-থাকা কলাম "দরকার" বলে
// ধরা পড়ত। স্ট্রিং-লিটারালও মুছে ফেলা হয় (একই কারণে)।
function sc_strip_sql_comments(string $sql): string
{
    $sql = preg_replace('~/\*.*?\*/~s', ' ', $sql) ?? $sql;
    $sql = preg_replace('~--[^\n]*~', ' ', $sql) ?? $sql;
    $sql = preg_replace('~#[^\n]*~', ' ', $sql) ?? $sql;
    // স্ট্রিং-লিটারাল (সহজ রূপ — এই ফাইলগুলোতে escape-করা কোট নেই)
    $sql = preg_replace("~'[^']*'~", "''", $sql) ?? $sql;
    return $sql;
}

// ADD-এর পরে যা এলে সেটা কলাম **নয়** (ইনডেক্স/কী/কনস্ট্রেইন্ট)।
function sc_not_column_words(): array
{
    return ['index', 'key', 'unique', 'constraint', 'primary', 'foreign', 'fulltext', 'spatial', 'check'];
}

// একটা মাইগ্রেশন ফাইলের লেখা থেকে দরকারি টেবিল ও কলামের তালিকা।
// ফেরায় ['tables' => ['t1', …], 'columns' => [['t', 'c'], …]]  (ক্রম অপরিবর্তিত, ডুপ্লিকেট বাদ)
function sc_parse_migration(string $sql): array
{
    $sql    = sc_strip_sql_comments($sql);
    $tables = [];
    $cols   = [];

    if (preg_match_all('~CREATE\s+TABLE(?:\s+IF\s+NOT\s+EXISTS)?\s+`?(\w+)`?~i', $sql, $m)) {
        foreach ($m[1] as $t) {
            $t = strtolower($t);
            if (!in_array($t, $tables, true)) { $tables[] = $t; }
        }
    }

    // স্টেটমেন্ট ধরে ভাঙা — প্রতিটা ALTER TABLE-এ একাধিক ADD COLUMN থাকতে পারে
    foreach (explode(';', $sql) as $stmt) {
        if (!preg_match('~ALTER\s+TABLE\s+`?(\w+)`?~i', $stmt, $mt)) { continue; }
        $table = strtolower($mt[1]);
        if (!preg_match_all('~\bADD\s+(?:COLUMN\s+)?(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?~i', $stmt, $mc)) { continue; }
        foreach ($mc[1] as $c) {
            $c = strtolower($c);
            if (in_array($c, sc_not_column_words(), true)) { continue; }
            $pair = [$table, $c];
            if (!in_array($pair, $cols, true)) { $cols[] = $pair; }
        }
    }

    return ['tables' => $tables, 'columns' => $cols];
}

