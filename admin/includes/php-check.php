/**
 * কোন শাখার কোন ভার্সনে বাগটা ঠিক হয়েছে।
 *
 * 🔴 এই তালিকায় যে শাখা **নেই** সেটাই "আয়ু শেষ" (end-of-life) ধরা হয় — আলাদা
 *    করে EOL তালিকা রাখা হয়নি, নাহলে দুটো তালিকা সময়ের সাথে আলাদা হয়ে যেত।
 * 🔴 নতুন কোনো CVE এলে শুধু এখানকার সংখ্যাগুলো বাড়ান — পাতার কোড ছুঁতে হবে না।
 */
function php_fixed_versions(): array
{
    return [
        '8.5' => '8.5.12',
        '8.4' => '8.4.27',
        '8.3' => '8.3.36',
        '8.2' => '8.2.35',
    ];
}

/** কোন শাখায় সরালে ভালো — সমর্থিত শাখাগুলোর মধ্যে সবচেয়ে নতুনটা নয়, স্থিরটা। */
function php_recommended_branch(): string
{
    return '8.4';
}

/** "8.1.34-5" / "8.4.27" → "8.1" / "8.4"; বোঝা না গেলে খালি স্ট্রিং। */
function php_branch(string $version): string
{
    if (!preg_match('/^(\d+)\.(\d+)/', trim($version), $m)) { return ''; }
    return $m[1] . '.' . $m[2];
}

/** ভার্সন স্ট্রিং থেকে শুধু `x.y.z` অংশটা (cPanel-এর `-5` জাতীয় লেজ বাদ)। */
function php_version_core(string $version): string
{
    if (!preg_match('/^(\d+\.\d+(?:\.\d+)?)/', trim($version), $m)) { return ''; }
    return $m[1];
}

/**
 * ini-র চালু/বন্ধ পড়া। PHP "1"/"on"/"true"/"yes" সবই চালু বোঝে, আর
 * `ini_get()` অচেনা directive-এ `false` দেয় — সেটাকে "বন্ধ" ধরা হয়।
 */
function php_ini_on($raw): bool
{
    if ($raw === false || $raw === null) { return false; }
    $v = strtolower(trim((string) $raw));
    return in_array($v, ['1', 'on', 'true', 'yes'], true);
}

/**
 * PHP2Shell-এর দৃষ্টিকোণ থেকে চলতি ভার্সনের অবস্থা।
 *
 * state:
 *   'ok'      — শাখা সমর্থিত **আর** ভার্সন প্যাচ করা ভার্সনের সমান/বেশি
 *   'old'     — শাখা সমর্থিত কিন্তু ভার্সন পুরনো → হোস্ট এখনো আপডেট করেনি
 *   'eol'     — শাখার আয়ু শেষ; PHP নিজে কোনো আপডেট দেয়নি
 *   'unknown' — ভার্সন স্ট্রিং পড়া যায়নি
 *
 * 🔴🔴 'eol'-এ **কখনো "ঝুঁকিতে" বা "নিরাপদ" কোনোটাই নিশ্চিত করে বলা হয় না**।
 *    কারণ cPanel ঐ শাখায় backport দিয়েছে (ea-php81 8.1.34-5, টিকিট EA-13611)
 *    কিন্তু backport-এ **ভার্সন নম্বর বদলায় না** — প্যাচ করা আর না-করা দুটোই
 *    "8.1.34" দেখায়। নিশ্চিত হতে প্যাকেজের changelog লাগে, যার জন্য WHM/root
 *    দরকার — শেয়ার্ড হোস্টিংয়ে ইউজারের সেটা নেই। তাই সৎ উত্তর একটাই:
 *    "যাচাই করা যায় না — সমর্থিত শাখায় সরান।"
 */
function php_security_status(string $version): array
{
    $branch = php_branch($version);
    $core   = php_version_core($version);
    $fixed  = php_fixed_versions();

    if ($branch === '' || $core === '') {
        return [
            'state'  => 'unknown',
            'branch' => '',
            'fixed'  => '',
            'label'  => 'ভার্সন পড়া যায়নি',
            'detail' => 'PHP ভার্সনটা বোঝা গেল না। cPanel → MultiPHP Manager-এ দেখে নিন।',
        ];
    }

    if (!isset($fixed[$branch])) {
        return [
            'state'  => 'eol',
            'branch' => $branch,
            'fixed'  => '',
            'label'  => 'PHP ' . $branch . ' — এই শাখার আয়ু শেষ',
            'detail' => 'PHP ' . $branch . '-এর জন্য PHP নিজে আর কোনো নিরাপত্তা আপডেট বের করে না। '
                . 'হোস্ট নিজে প্যাচ বসিয়ে থাকলেও ভার্সন নম্বর বদলায় না, তাই এখান থেকে যাচাই করা '
                . 'সম্ভব নয়। cPanel → MultiPHP Manager-এ গিয়ে ডোমেইনটা PHP '
                . php_recommended_branch() . '-এ সরিয়ে দিন — ওখানে সংখ্যা দেখেই নিশ্চিত হওয়া যায়।',
        ];
    }

    $need = $fixed[$branch];
    if (version_compare($core, $need, '>=')) {
        return [
            'state'  => 'ok',
            'branch' => $branch,
            'fixed'  => $need,
            'label'  => 'PHP ' . $core . ' — প্যাচ করা আছে',
            'detail' => 'এই শাখায় PHP2Shell-এর ফিক্স এসেছে ' . $need . '-এ, আপনি তার সমান বা নতুন ভার্সনে আছেন।',
        ];
    }

    return [
        'state'  => 'old',
        'branch' => $branch,
        'fixed'  => $need,
        'label'  => 'PHP ' . $core . ' — পুরনো, প্যাচ লাগবে',
        'detail' => 'এই শাখার ফিক্স ' . $need . '-এ এসেছে, আপনি ' . $core . '-এ আছেন। '
            . 'হোস্টিং কোম্পানিকে বলুন PHP প্যাকেজ আপডেট করতে — এটা আপনি বা আমি পারি না।',
    ];
}

/** `.user.ini` / INI Editor-এর সুরক্ষাটা সত্যিই বসেছে কিনা + কী করতে হবে। */
function php_upload_progress_status($raw): array
{
    if (!php_ini_on($raw)) {
        return [
            'ok'     => true,
            'label'  => 'session.upload_progress বন্ধ',
            'detail' => 'CVE-2026-109619-এর প্রমাণিত পথটা বন্ধ আছে। (এটা সম্পূর্ণ সমাধান নয় — আসল কাজ PHP আপডেট।)',
        ];
    }

    return [
        'ok'     => false,
        'label'  => 'session.upload_progress চালু',
        'detail' => 'অপেক্ষার সময়ের ঢাল হিসেবে এটা বন্ধ করা যায়: cPanel → MultiPHP INI Editor → '
            . 'Editor Mode → ডোমেইন বেছে → নিচের লাইনটা যোগ করে Save — '
            . 'session.upload_progress.enabled = 0 '
            . '(রিপোর `.user.ini` ফাইলটা এই কাজই করে, কিন্তু কিছু হোস্ট-কনফিগারেশনে ওটা উপেক্ষিত হয়।)',
    ];
}
