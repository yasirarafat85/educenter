//   PHP আলাদা হতে পারে — তাই "এই মুহূর্তে পাতাটা কোন PHP-তে চলছে" সেটা
//   **ওয়েব রিকোয়েস্টের ভেতর থেকেই** দেখানো দরকার। এই ফাইল সেই হিসাবটাই করে।
